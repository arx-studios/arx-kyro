// Generates src/types.ts: one `export type X = components['schemas']['X']` alias per schema,
// derived from the generated src/schema.d.ts. Run as part of `pnpm generate`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const schemaPath = fileURLToPath(new URL('src/schema.d.ts', root));
const outPath = fileURLToPath(new URL('src/types.ts', root));

const src = readFileSync(schemaPath, 'utf8');
const start = src.indexOf('    schemas: {');
const end = src.indexOf('    responses:', start);
if (start < 0 || end < 0) {
  throw new Error('Could not locate components.schemas in schema.d.ts');
}
const names = [...src.slice(start, end).matchAll(/^ {8}(\w+): /gm)].map((m) => m[1]);

const lines = [
  '// AUTO-GENERATED by scripts/gen-aliases.mjs from src/schema.d.ts. Do not edit.',
  "import type { components } from './schema';",
  '',
  ...names.map((n) => `export type ${n} = components['schemas']['${n}'];`),
  '',
];
writeFileSync(outPath, lines.join('\n'));
console.log(`Wrote ${names.length} schema aliases to src/types.ts`);
